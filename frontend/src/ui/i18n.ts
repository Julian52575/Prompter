export const DICTS: Record<Language, Dict> = { en, fr };

/** Built-in wording shown in the UI language; anything else (user text) is returned as is. */
export const tr = (d: Dict, s: string) => d.builtinText[s] ?? s;

function localizeField(d: Dict, f: Field): Field {
  const base = { ...f, label: tr(d, f.label) } as Field;
  switch (base.type) {
    case "text":
    case "longtext":
      return base.hint ? { ...base, hint: tr(d, base.hint) } : base;
    case "choice":
      return { ...base, options: base.options.map((o) => ({ ...o, label: tr(d, o.label) })) };
    case "list":
      return { ...base, itemLabel: tr(d, base.itemLabel), noteLabel: tr(d, base.noteLabel) };
    case "group":
      return {
        ...base,
        itemLabel: tr(d, base.itemLabel),
        defaultItems: base.defaultItems?.map((n) => tr(d, n)),
        children: base.children.map((c) => localizeField(d, c)),
      };
  }
}

/**
 * The template as the form shows it. Only labels change: ids, values and the
 * wording the prompt is built from stay as they are, so prompts stay English.
 */
export function localizeTemplate(d: Dict, t: Template): Template {
  return { ...t, name: tr(d, t.name), fields: t.fields.map((f) => localizeField(d, f)) };
}

export const localizeMode = (d: Dict, m: ReplyMode): ReplyMode => ({ ...m, label: tr(d, m.label) });
